/**
 * 機組單元的高程對齊修正。
 *
 * 機房內有兩台機組，多數 GLB 以兩個頂層節點各放一份。13 個檔案的兩份完全同高
 * （ΔY = 0.00），但有 7 個檔案的兩份高度不一致，最嚴重的是發電機本體差 1.01 m。
 *
 * 這是模型本身的問題，不是檢視器的。在此以節點層級的 Y 位移修正，
 * 與參考專案 TaipeiCityHall 的 `FLOOR_Y_OFFSET`（修正樓層原生高程不對）同一個做法。
 * 模型日後在 Blender 修好後，把對應項目從這裡刪掉即可。
 *
 * 位移值 = 左側那一份的最低 Y − 右側那一份的最低 Y，即把右側對齊到左側。
 *
 * ⚠️ 這是「一律對齊左側」的結果，不是逐件依實體參照校正的結果。已知副作用：
 *   - p09 發電機本體：兩台都會陷入避震基座約 0.7 m（左側那一份原本就是這樣）
 *   - p06 組合式煙囪：右側原本對準穿牆蓋板，對齊後會與蓋板差 0.50 m
 *   - p04 消音器重型吊架：右側原本坐在消音器上方，對齊後會穿進消音器 0.21 m
 */

/** 兩台機組的 Z 分界（模型原始座標）。小於此值為畫面右側那一組 */
